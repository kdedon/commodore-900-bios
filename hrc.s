/ Hi-res console on the 640x400 colour board: 80x25 cells of 8x16
/ pixels, four bits a pixel, 320 bytes a raster, pixel 0 in the top
/ nibble.  The bitmap is segments 3A and 3B; row 12 crosses them.
/ Entered from avidchr with the char in rl1, the cell number in r13 and
/ the return in rr10, without a stack.  Keeps r3 and r10-r15, exits
/ with r0 clear.
/ Past the screen, 3B:F400 on: how many cells of each row may have ink,
/ a scroll's register save, and a black raster.
#if ROMKB > 32
	.globl	cvidchr_

RB	= 320
NCOL	= 80
NCELL	= 2000
EXT	= 0xf400
SAVE	= 0x3b00f480
ZERO	= 0x3b00f500

/ rh1, what to do once a cell is drawn
PUT	= 0
NL	= 1
BS	= 2
CUR	= 3

cvidchr_:
	ld	r9, r3
home:
	test	r13
	jr	nz, 1f
	ldl	rr2, $0x3a000000	/ at home: clear the screen
	ld	@rr2, $0
	ldl	rr4, rr2
	inc	r5, $2
	ld	r8, $0x8000
	ldir	@rr4, @rr2, r8
	ldl	rr2, $0x3b000000
	ld	@rr2, $0
	ldl	rr4, rr2
	inc	r5, $2
	ld	r8, $0x7b20		/ the screen and the area past it
	ldir	@rr4, @rr2, r8
	ldb	rl5, $0xff
	outb	0x0404, rl5
1:
	cpb	rl1, $0x0a
	jr	z, nl
	cpb	rl1, $0x0c
	jr	z, ff
	cpb	rl1, $0x08
	jr	z, bs
	cpb	rl1, $0x20
	jr	ult, cur
	cpb	rl1, $0x7e
	jr	ugt, cur
	ldb	rh1, $PUT
	jr	draw
nl:
	ldb	rh1, $NL
	ldb	rl1, $0x20
	jr	draw
bs:
	ld	r7, r13
	clr	r6
	div	rr6, $NCOL
	test	r6
	jr	z, cur		/ at the left edge
	ldb	rh1, $BS
	ldb	rl1, $0x20
	jr	draw
ff:
	clr	r13
	clrb	rl1
	jr	home
cur:
	ldb	rh1, $CUR
	ldb	rl1, $0x5f

/ Draw rl1 at cell r13, then go on by rh1.
draw:
	ld	r7, r13
	clr	r6
	div	rr6, $NCOL	/ r7 row, r6 column
	ld	r2, $0x3b00
	ld	r3, $EXT
	add	r3, r7
	ldb	rh0, rl6
	incb	rh0, $1
	ldb	rl0, @rr2
	cpb	rh0, rl0
	jr	ule, 1f
	ldb	@rr2, rh0
1:
	ld	r5, r7
	mult	rr4, $16*RB
	sll	r6, $2
	ld	r7, r6
	clr	r6
	addl	rr4, rr6
	ld	r2, r4		/ the segment: 3A, or 3B past 64K
	sll	r2, $8
	add	r2, $0x3a00
	ld	r3, r5
	ldb	rl7, rl1
	clrb	rh7
	sub	r7, $0x20
	sll	r7, $4
	lda	rr4, cfont_
	add	r5, r7
	ld	r8, $16
2:
	ldb	rl0, @rr4
	inc	r5, $1
	clrb	rh0
	ld	r7, r0
	srl	r7, $3
	and	r7, $0x1e
	ld	r6, cnib(r7)
	ld	r7, r0
	and	r7, $0x0f
	add	r7, r7
	ld	r7, cnib(r7)
	ldl	@rr2, rr6
	add	r3, $RB
	jr	nc, 3f
	add	r2, $0x0100
3:
	djnz	r8, 2b
	cpb	rh1, $NL
	jr	z, donl
	cpb	rh1, $BS
	jr	z, dobs
	cpb	rh1, $CUR
	jr	z, done
	inc	r13, $1
	jr	chkend
donl:
	ld	r7, r13
	clr	r6
	div	rr6, $NCOL
	inc	r7, $1
	mult	rr6, $NCOL
	ld	r13, r7
chkend:
	cp	r13, $NCELL
	jr	ult, cur
	jr	scroll
dobs:
	dec	r13, $1
	jr	cur
done:
	ld	r3, r9
	clr	r0
	jp	@rr10

/ Move rows 1-24 up a row and clear row 24: rasters 2-13, which hold
/ all the ink, as far across as the rows have any.  A raster is moved
/ in two pieces, columns 0-63 and 64-79, so neither crosses 3A/3B.
scroll:
	ldl	rr2, $SAVE
	ldm	@rr2, r9, $5
	clr	r0
srow:
	ld	r2, $0x3b00
	ld	r3, $EXT
	add	r3, r0
	ldb	rl1, @rr2
	inc	r3, $1
	ldb	rh1, @rr2
	dec	r3, $1
	ldb	@rr2, rh1
	cpb	rl1, rh1
	jr	uge, 1f
	ldb	rl1, rh1
1:
	clrb	rh1
	cp	r1, $NCOL
	jr	ule, 2f
	ld	r1, $NCOL
2:
	test	r1
	jr	z, snext
	ld	r5, r0
	mult	rr4, $16*RB
	addl	rr4, $2*RB
	sll	r4, $8
	add	r4, $0x3a00
	ld	r3, r0
	inc	r3, $1
	mult	rr2, $16*RB
	addl	rr2, $2*RB
	sll	r2, $8
	add	r2, $0x3a00
	ld	r12, $RB
	jr	smove
snext:
	inc	r0, $1
	cp	r0, $24
	jr	ult, srow
	ld	r2, $0x3b00		/ row 24 from the black raster
	ld	r3, $EXT+24
	ldb	rl1, @rr2
	clrb	@rr2
	clrb	rh1
	cp	r1, $NCOL
	jr	ule, 3f
	ld	r1, $NCOL
3:
	test	r1
	jr	z, sdone
	ld	r5, $24
	mult	rr4, $16*RB
	addl	rr4, $2*RB
	sll	r4, $8
	add	r4, $0x3a00
	ldl	rr2, $ZERO
	clr	r12

/ r1 cells of 12 rasters to rr4 from rr2, rr2 moving on by r12.
smove:
	ld	r11, $12
sras:
	ld	r10, r1
	cp	r10, $64
	jr	ule, 4f
	ld	r10, $64
4:
	add	r10, r10
	ldl	rr6, rr2
	ldl	rr8, rr4
	ldir	@rr8, @rr6, r10
	cp	r1, $64
	jr	ule, 7f
	ld	r10, r1
	sub	r10, $64
	add	r10, r10
	ldl	rr6, rr2
	add	r7, $256
	jr	nc, 5f
	add	r6, $0x0100
5:
	ldl	rr8, rr4
	add	r9, $256
	jr	nc, 6f
	add	r8, $0x0100
6:
	ldir	@rr8, @rr6, r10
7:
	add	r3, r12
	jr	nc, 8f
	add	r2, $0x0100
8:
	add	r5, $RB
	jr	nc, 9f
	add	r4, $0x0100
9:
	djnz	r11, sras
	cp	r0, $24
	jr	ult, snext
sdone:
	ldl	rr2, $SAVE
	ldm	r9, @rr2, $5
	ld	r13, $NCELL-NCOL
	jp	cur

